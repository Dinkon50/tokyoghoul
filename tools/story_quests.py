def const(q_id):
    return q_id.upper()


def java():
    lines = []
    for chain, quests in CHAINS.items():
        lines.append(f'    // ---- {chain}')
        for (qid, trig, goal, pts, blood, act, *_rest) in quests:
            b = 'null' if blood is None else str(blood)
            lines.append(f'    {const(qid)}("{qid}", Chain.{chain}, Trigger.{trig}, {goal}, {pts}, {act}, {b}),')
    out = '\n'.join(lines)
    return out[:-1] + ';'


def lang():
    d = {}
    for chain, acts in ACTS.items():
        for i, name in enumerate(acts, 1):
            d[f'quest.tokyoghoulrpg.act.{chain.lower()}.{i}'] = f'Глава {["I", "II", "III", "IV", "V"][i - 1]}. {name}'
    for chain, quests in CHAINS.items():
        for (qid, trig, goal, pts, blood, act, title, desc, story) in quests:
            d[f'quest.tokyoghoulrpg.{qid}'] = title
            d[f'quest.tokyoghoulrpg.{qid}.desc'] = desc
            d[f'quest.tokyoghoulrpg.{qid}.story'] = story
    return d


