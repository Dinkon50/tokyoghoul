"""Иконка учебной квинке 16 x 16: клинок по диагонали, сталь с красной жилой, чёрная рукоять, бирюзовый кейс-шарнир."""
import sys
from PIL import Image

def icon():
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    def p(x, y, c):
        img.putpixel((x, y), c + (255,))
    # клинок: от (14,1) к (6,9), ширина 2-3
    for i in range(9):
        x, y = 14 - i, 1 + i
        p(x, y, (232, 236, 240))            # светлая кромка
        p(x, y + 1, (178, 34, 46) if 2 <= i <= 6 else (196, 202, 210))   # красная жила RC
        if x + 1 < 16 and y + 1 < 16:
            p(x + 1, y + 1, (130, 138, 150))    # тёмная сторона
    p(15, 0, (250, 250, 252))
    # гарда
    for x, y in ((4, 9), (5, 9), (6, 10), (7, 11), (8, 11)):
        p(x, y, (40, 200, 180))
    p(6, 9, (20, 120, 110)); p(7, 10, (20, 120, 110))
    # рукоять
    for i in range(4):
        p(5 - i, 11 + i, (34, 30, 34))
        p(4 - i, 11 + i, (60, 52, 58)) if 4 - i >= 0 else None
    p(1, 15, (40, 200, 180)); p(0, 15, (20, 120, 110))
    return img

if __name__ == "__main__":
    icon().save(sys.argv[1])
    icon().resize((192, 192), Image.NEAREST).save("/tmp/claude-0/art/quinque_prev.png")
