"""
Сила боссов мода: насколько каждый опасен и насколько его долго убивать. По этим числам подобраны
здоровье, урон и атаки боссов стилей боя («чуть выше среднего»).

Запуск: python3 boss_power.py

Как считается
-------------
* Живучесть (эффективное здоровье) = здоровье x число полных полосок (полугуль восстанавливается один раз,
  Монарх — дважды) / (1 - доля урона, которую съедает броня) x защитные приёмы (стойка, уклонение).
  Броню считаем по правилу Minecraft для удара игрока в 10 урона.
* Урон в секунду = обычный удар раз в секунду + урон каждой особой атаки / её откат.
  У стадий берём среднее по бою: первая половина здоровья — обычная, вторая — усиленная.
* Сила = корень из (живучесть x урон в секунду). Если у босса вдвое больше здоровья, сила растёт в 1,41 раза,
  если вдвое больше и здоровья, и урона — в 2 раза.
* Множители сложности и общий бонус боссов (+40% здоровья, +25% урона) одинаковы у всех: на сравнение не влияют.
* Призывы (гули, агенты, полугули) не считаем: их можно не трогать.

Что такое «среднее»
-------------------
Боссы мода очень разные: Алый Монарх в 17 раз сильнее Пожирателя. Обычное среднее арифметическое тянется к
самому сильному (оно выше Кровавого полугуля, рейд-босса для группы), поэтому берём среднее геометрическое —
«середину» на шкале «во сколько раз сильнее». Цель для боссов стилей — на 15% выше него.
"""
import math

REF_HIT = 10.0      # удар игрока, по которому считаем броню


def armor_cut(armor, tough=0.0, hit=REF_HIT):
    """Доля урона, которую съедает броня (формула Minecraft 1.20)."""
    eff = max(armor / 5.0, armor - hit / (2.0 + tough / 4.0))
    return min(20.0, eff) / 25.0


def ehp(hp, bars, armor, tough, defense=1.0):
    return hp * bars / (1.0 - armor_cut(armor, tough)) * defense


def power(e, dps):
    return math.sqrt(e * dps)


# ---------------------------------------------------------------- боссы, которые уже есть
def existing():
    rows = []
    # Пожиратель: 250, удар 10, броня 6; прыжок 8 урона раз в 8 с; бешенство ниже 30%: урон +20%
    dps = (10 + 8 / 8) * (0.7 + 0.3 * 1.2)
    rows.append(("Пожиратель", 250, 10, ehp(250, 1, 6, 0), dps))
    # Старший следователь: 320, удар 3 + квинке IXA (6 + 4) = 13, броня 10
    sp = 10 / 6 + 7 / 10 + 8 / 8 + 9 / 9 + 8 / 13          # рывок, круговой, прыжок, разряд, молния
    rows.append(("Старший следователь", 320, 13, ehp(320, 1, 10, 0), 13 + sp))
    # Кровавый полугуль: 750 x 2 стадии, удар 30, броня 14/6; особые x3, во второй стадии урон x1.25, откат x0.7
    base = 8 / 8 + 10 / 6 + 7 / 10 + 2.5 * 5 / 7 + 9 / 12 + 7 / 11
    p1 = 30 + 3 * base
    p2 = 30 * 1.25 + 3 * 1.25 * (base + 5 / 14) / 0.7      # шипы из земли — только во второй
    rows.append(("Кровавый полугуль", 750, 30, ehp(750, 2, 14, 6), (p1 + p2) / 2))
    # Алый Монарх: 1000 x 3 стадии, удар 40, броня 18/8; особые x4; урон +25% и откат 0.85/0.65/0.5 по стадиям
    base_m = base + 5 / 14 + 9 / 9 + 8 / 13
    ph = [(1.0, 0.85), (1.25, 0.65), (1.5, 0.5)]
    dps_m = sum(40 * d + 4 * d * base_m / cd for d, cd in ph) / 3
    rows.append(("Алый Монарх", 1000, 40, ehp(1000, 3, 18, 8), dps_m))
    return rows


# ---------------------------------------------------------------- боссы стилей
# Вторая половина здоровья у всех трёх: урон x1.15, откат особых x0.75, скорость +20%
P2_DAMAGE, P2_COOLDOWN = 1.15, 0.75


def two_phase(melee, specials_per_sec, extra=1.0):
    p1 = melee + specials_per_sec
    p2 = melee * P2_DAMAGE + P2_DAMAGE * specials_per_sec / P2_COOLDOWN
    return (p1 + p2) / 2 * extra


STYLE_BOSSES = [
    # имя, удар, особые атаки (урон / откат в секундах), броня, прочность, защита, множитель урона
    ("Мастер додзё (Боец)", 17,
     # шквал: 4 удара по 4.5 + последний x1.6 раз в 7 с; удар ладонью 16 раз в 8 с;
     # контрудар 20 после стойки раз в 10 с, срабатывает примерно в половине стоек
     [(4 * 4.5 + 4.5 * 1.6, 7), (16, 8), (20 * 0.5, 10)],
     12, 4,
     # стойка 2 с из 10 (20% времени), спереди гасит 80% урона, спереди бьют примерно в 70% случаев
     1 / (1 - 0.2 * 0.8 * 0.7), 1.0),
    ("Клоун из Пьеро (Тень)", 15,
     # удар из тени 22 раз в 9 с; веер ножей 5 x 3.5 раз в 7 с; двое двойников ~4 урона в секунду
     [(22, 9), (5 * 3.5, 7), (4 * 20, 20)],
     6, 0,
     # уклоняется от каждого 4-го удара вблизи (x1.33) и 1,5 с из 9 невидим (x1.2)
     1 / (1 - 0.25) * 1.2, 1.0),
    ("Белый жнец (Жнец)", 20,
     # выпад 18 раз в 6 с; казнь 30 раз в 12 с (по цели с малым здоровьем — примерно половина случаев)
     [(18, 6), (30 * 0.5, 12)],
     14, 6, 1.0,
     # метка смерти: +20% урона по цели 6 с из 15
     1 + 0.2 * 6 / 15),
]


def main():
    rows = existing()
    print(f"{'Босс':<24}{'здор.':>7}{'удар':>6}{'живуч.':>9}{'урон/с':>8}{'сила':>8}")
    powers = []
    for name, hp, melee, e, dps in rows:
        p = power(e, dps)
        powers.append(p)
        print(f"{name:<24}{hp:>7}{melee:>6}{e:>9.0f}{dps:>8.1f}{p:>8.1f}")
    arith = sum(powers) / len(powers)
    geo = math.exp(sum(math.log(p) for p in powers) / len(powers))
    target = geo * 1.15
    print(f"\nсреднее арифметическое {arith:.0f} (тянется к Монарху), геометрическое {geo:.0f}")
    print(f"цель «чуть выше среднего» = геометрическое x 1.15 = {target:.0f}\n")

    print("Боссы стилей: здоровье подобрано под цель")
    for name, melee, specials, armor, tough, defense, dmg_mult in STYLE_BOSSES:
        sp = sum(d / cd for d, cd in specials)
        dps = two_phase(melee, sp, dmg_mult)
        need_ehp = target * target / dps
        hp = need_ehp * (1 - armor_cut(armor, tough)) / defense
        hp = round(hp / 10) * 10
        e = hp / (1 - armor_cut(armor, tough)) * defense
        print(f"{name:<24} здоровье {hp:>5}, удар {melee:>3}, броня {armor:>2}/{tough}, урон/с {dps:5.1f}, "
              f"живуч. {e:6.0f}, сила {power(e, dps):6.1f}")


if __name__ == "__main__":
    main()


# ---------------------------------------------------------------- данж «Глубины 24-го района»
# Особые атаки (урон / откат) — те же, что у Кровавого полугуля, умноженные на силу особых атак босса.
LEAP, CHARGE, SWEEP, SHARDS, SPEAR, NOVA, SPIKES = (8, 8), (10, 6), (7, 10), (12.5, 7), (9, 12), (7, 11), (5, 14)


def kit_dps(melee, specials, mult, cd=1.0, dmg=1.0):
    return melee * dmg + sum(d * mult * dmg / (c * cd) for d, c in specials)


DEEP = {
    # Стражи: одна полоса здоровья, цель ~270 (сильнее боссов стилей)
    "Страж глубин: Жало": dict(target=270, melee=22, armor=14, tough=4, bars=1,
                               dps=kit_dps(22, [SPEAR, CHARGE, SWEEP, LEAP], 1.6)),
    "Страж глубин: Крыло": dict(target=270, melee=20, armor=12, tough=3, bars=1,
                                dps=kit_dps(20, [SHARDS, NOVA, CHARGE, LEAP], 1.8)),
    # Древний гуль: две полные полосы, вторая — урон x1.25, откат x0.6; цель ~600 (между полугулем и Монархом)
    "Древний гуль": dict(target=600, melee=32, armor=16, tough=6, bars=2,
                         dps=(kit_dps(32, [LEAP, CHARGE, SWEEP, SHARDS, SPEAR, NOVA], 2.2, 0.85)
                              + kit_dps(32, [LEAP, CHARGE, SWEEP, SHARDS, SPEAR, NOVA, SPIKES], 2.2, 0.6, 1.25)) / 2),
}


def deep():
    print("\nДанж «Глубины 24-го района»: здоровье одной полосы подобрано под цель")
    for name, b in DEEP.items():
        cut = armor_cut(b["armor"], b["tough"])
        need = b["target"] ** 2 / b["dps"]
        hp = round(need * (1 - cut) / b["bars"] / 10) * 10
        e = ehp(hp, b["bars"], b["armor"], b["tough"])
        print(f"{name:<24} здоровье {hp:>5} x{b['bars']}, удар {b['melee']:>3}, броня {b['armor']}/{b['tough']}, "
              f"урон/с {b['dps']:5.1f}, сила {power(e, b['dps']):6.1f}")


if __name__ == "__main__":
    deep()
